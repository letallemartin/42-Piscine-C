void    ft_rev_int_tab(int *tab, int size)
{
    int    i;
    int    temp;
    i = 0;

    while (size - 1 > i)
    {
        temp = tab[size - 1];
        tab[size - 1] = tab[i];
        tab[i] = temp;
        i++;
        size--;
    }
}

